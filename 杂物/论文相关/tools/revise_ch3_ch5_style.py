REGEX_REPLACEMENTS = [
    (r"见下表\s*([0-9]-[0-9]+)", r"见表 \1"),
    (r"见表([0-9]-[0-9]+)", r"见表 \1"),
    (r"如表([0-9]-[0-9]+)所示", r"如表 \1 所示"),
    (r"下图([0-9]-[0-9]+)展示了", r"图 \1 展示"),
    (r"下图([0-9]-[0-9]+)展示", r"图 \1 展示"),
]


def set_paragraph_text(paragraph, text: str) -> None:
    if paragraph.text == text:
        return
    runs = paragraph.runs
    if runs:
        runs[0].text = text
        for run in runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(text)


def rewrite_text(text: str) -> str:
    import re

    new = text
    for old, replacement in REPLACEMENTS:
        new = new.replace(old, replacement)
    for pattern, replacement in REGEX_REPLACEMENTS:
        new = re.sub(pattern, replacement, new)
    return new


def iter_paragraphs(doc: Document):
    yield from doc.paragraphs
    # Only prose/caption paragraphs are rewritten. Table contents are left intact
    # because the user marked tables and code samples as already concise.


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for src_name, out_name in FILES.items():
        doc = Document(str(BASE / src_name))
        changed = 0
        for paragraph in iter_paragraphs(doc):
            original = paragraph.text
            revised = rewrite_text(original)
            if revised != original:
                set_paragraph_text(paragraph, revised)
                changed += 1
        out_path = OUT_DIR / out_name
        doc.save(str(out_path))
        print(f"{src_name} -> {out_path} ({changed} paragraphs changed)")


if __name__ == "__main__":
    main()
